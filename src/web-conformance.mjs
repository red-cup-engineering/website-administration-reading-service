import { readFileSync } from "node:fs";
import path from "node:path";
import { walkPosixPathsSync } from "@red-cup-engineering/computer-filepath-engineering-services-section/walk-posix-paths";
import { deriveWebSourceRoles } from "./web-source-roles.mjs";
import { inspectWebSource, SERVER, TUFTE, LEGACY_SERVERS } from "./web-source-evidence.mjs";

export const WEB_SOURCE_SCOPE = Object.freeze({
  kind: "web-source-conformance.scope", version: 1,
  includes: "All package manifests, JS/TS/JSX, HTML/templates, common server languages, deployment/build configuration below the explicit root, including legacy, examples and private UI.",
  excludes: [".git", "node_modules", ".pnpm-store", ".venv", "venv", "__pycache__", ".cache", ".next", ".nuxt", ".env*", "*.wif"],
  evidence: "Authored source and configuration only. No claim about publication, installation, activation, browser quality, or live deployment. Documentary or historical custody without an inbound declared runtime, deployment, or generator edge is outside the current application graph, not proof of global inactivity. Dynamic or unsupported application links remain unknown.",
});
const js = /\.[cm]?[jt]sx?$/i;
const html = /\.(?:html?|hbs|ejs|njk|vue|svelte)$/i;
const other = /\.(?:py|go|rs|rb|php|java|clj|ex|exs|fnl|lua|sh)$/i;
const config = /(?:^|\/)(?:package\.json|lake-manifest\.json|tsconfig(?:\.[^/]+)?\.json|site-admin\.config\.json|wrangler(?:\.[^/]*)?\.(?:jsonc?|toml)|(?:hugo|config)\.(?:toml|ya?ml)|(?:Dockerfile|Caddyfile)(?:\.[^/]*)?|[^/]+\.(?:service|ya?ml))$/i;
const asset = /\.(?:json|css|scss|sass|less|svg|png|jpe?g|gif|webp|avif|ico|woff2?|ttf|wasm)$/i;
const supported = (name) => js.test(name) || html.test(name) || other.test(name) || config.test(name);
const fixture = (name) => /(?:^|\/)(?:test|tests|__tests__|fixtures|__fixtures__)(?:\/)|\.(?:test|spec)\.[^.]+$/.test(name);
const generated = (name, text) => /(?:^|\/)(?:dist|build|out|_site|_public)(?:\/)/.test(name) || /(?:generated by|auto-generated|do not edit)/i.test(text.slice(0, 500));
const historical = (name) => /(?:^|\/)(?:legacy|archive|triage)(?:\/)|(?:^|\/)content\/text\/|(?:^|\/)data\/(?:records|logs)\//.test(name);
const applicationPath = (name) => /(?:^|[\/_.-])(?:server|worker|serve|frontend|website|browser|web)(?:[\/_.-]|$)/.test(name);
const inside = (file, root) => root === "." || file === root || file.startsWith(`${root}/`);

/**
 * @typedef {{path:string,text?:string,error?:string,kind?:string}} SourceInput
 * @typedef {{root:string,files:SourceInput[],issues:object[],scope:object}} WebSourceSnapshot
 * @typedef {{status:'conformant'|'nonconformant'|'unknown'|'not-applicable', reasons:string[], evidence:object[]}} Conformance
 */

/** Explicit filesystem boundary. Does not follow symlinks or read secrets.
 * @param {string} root
 * @param {{walk?:Function,read?:Function}} [adapters]
 * @returns {WebSourceSnapshot}
 */
export function readWebSourceSnapshot(root, { walk = walkPosixPathsSync, read = readFileSync } = {}) {
  if (typeof root !== "string" || !root) throw new TypeError("root required");
  const absoluteRoot = path.resolve(root), issues = [], files = [], assets = [];
  let observed;
  try { observed = walk({ root: absoluteRoot, excludes: WEB_SOURCE_SCOPE.excludes, includeFile: (entry) => supported(entry.path), inspectEntry: (entry) => { if (entry.kind === "file" && !supported(entry.path) && asset.test(entry.path)) assets.push(entry.path); }, symlinks: "record", unreadable: "throw", missing: "throw" }); }
  catch (error) { return { root: absoluteRoot, files, issues: [{ path: ".", reason: "discovery-failed", code: error.code ?? "unknown" }], scope: WEB_SOURCE_SCOPE }; }
  if (observed.truncated || observed.skipped) issues.push({ path: ".", reason: "incomplete-discovery", skipped: observed.skipped, truncated: observed.truncated });
  for (const entry of observed.files) {
    if (entry.kind === "symlink") { if (supported(entry.path)) issues.push({ path: entry.path, reason: "unresolved-source-symlink" }); continue; }
    try { files.push({ path: entry.path, text: read(path.join(absoluteRoot, entry.path), "utf8") }); }
    catch (error) { files.push({ path: entry.path, error: error.code ?? "unreadable" }); }
  }
  return { root: absoluteRoot, files, assets, issues, scope: WEB_SOURCE_SCOPE };
}

/** Pure projection; complete candidate records accompany every failure.
 * @param {WebSourceSnapshot} snapshot
 * @returns {object}
 */
export function projectWebConformance(snapshot) {
  if (!snapshot || !Array.isArray(snapshot.files) || !Array.isArray(snapshot.issues)) throw new TypeError("source snapshot required");
  const assets = new Set(snapshot.assets ?? []);
  const files = new Map(), manifests = new Map(), issues = [...snapshot.issues], records = [], configs = [];
  for (const input of [...snapshot.files].sort((a, b) => a.path.localeCompare(b.path))) {
    if (typeof input.path !== "string" || path.posix.isAbsolute(input.path) || input.path.split("/").includes("..") || files.has(input.path)) throw new TypeError("unique relative source paths required");
    const file = { ...input, source: null, manifest: null, generated: false, producers: [], references: [], dependencies: [], missingTargets: [] };
    files.set(file.path, file);
    if (file.error || typeof file.text !== "string") { issues.push({ path: file.path, reason: "unreadable-input", code: file.error ?? "missing-text" }); continue; }
    file.generated = generated(file.path, file.text);
    if (path.posix.basename(file.path) === "package.json") {
      try { file.manifest = JSON.parse(file.text); manifests.set(path.posix.dirname(file.path), file.manifest); }
      catch { issues.push({ path: file.path, reason: "invalid-package-manifest" }); }
    } else if (js.test(file.path) && !/\.d\.[cm]?ts$/.test(file.path)) file.source = inspectWebSource(file);
    if (config.test(file.path) && !file.manifest && (/(?:wrangler|site-admin\.config|Dockerfile|Caddyfile|\.service$|(?:^|\/)\.github\/workflows\/)/.test(file.path)
      || /(?:^|\/)(?:hugo|config)\.(?:toml|ya?ml)$/.test(file.path) && (/(?:^|\/)hugo\./.test(file.path) || /^\s*baseURL\s*[:=]/mi.test(file.text))
      || /^kind:\s*(?:Deployment|Service|Ingress|Pod|StatefulSet)\b/m.test(file.text))) configs.push(file);
  }
  const ownerCache = new Map(), directories = new Set();
  const owner = (name) => {
    let directory = path.posix.dirname(name);
    const walked = [];
    while (!manifests.has(directory) && !ownerCache.has(directory) && directory !== ".") {
      walked.push(directory); directory = path.posix.dirname(directory);
    }
    const result = manifests.has(directory) ? directory : ownerCache.get(directory) ?? null;
    for (const entry of walked) ownerCache.set(entry, result);
    return result;
  };
  for (const name of files.keys()) {
    let directory = path.posix.dirname(name);
    while (directory !== "." && !directories.has(directory)) { directories.add(directory); directory = path.posix.dirname(directory); }
  }
  const resolve = (from, specifier) => {
    if (!specifier?.startsWith(".")) return null;
    const base = path.posix.normalize(path.posix.join(path.posix.dirname(from), specifier));
    return [base, ...[".mjs", ".mts", ".js", ".ts", ".jsx", ".tsx", "/index.mjs", "/index.ts", "/index.js"].map((suffix) => base + suffix), base.replace(/\.mjs$/, ".mts"), base.replace(/\.js$/, ".ts")].find((name) => files.has(name)) ?? null;
  };
  for (const file of files.values()) {
    file.owner = owner(file.path);
    for (const entry of file.source?.imports ?? []) {
      const target = resolve(file.path, entry.specifier);
      if (target) file.dependencies.push(target);
      else if (entry.specifier?.startsWith(".")) {
        const resource = path.posix.normalize(path.posix.join(path.posix.dirname(file.path), entry.specifier));
        if (!assets.has(resource)) file.source.unknowns.push("unresolved-relative-import");
      }
    }
  }

  const roles = deriveWebSourceRoles(files, manifests, [TUFTE, SERVER]);
  // Deployment and build declarations retain references even when they point
  // into legacy directories; they are configuration evidence, never live proof.
  for (const file of configs) {
    if (historical(file.path) || roles.installed.has(file.path) || roles.testOutputs.has(file.path)) continue;
    if (/wrangler/.test(file.path)) {
      const main = file.text.match(/(?:["']main["']|\bmain)\s*[:=]\s*["']([^"']+)["']/)?.[1];
      if (main) {
        const target = path.posix.normalize(path.posix.join(path.posix.dirname(file.path), main));
        if (!files.has(target)) file.missingTargets.push(target);
      }
    }
    const literals = [...file.text?.matchAll(/["']([^"'\n]+)["']/g) ?? []].map((match) => match[1]);
    for (const value of literals) {
      const relative = path.posix.normalize(path.posix.join(path.posix.dirname(file.path), value));
      const exact = files.has(value) ? value : files.has(relative) ? relative : null;
      if (exact) files.get(exact).references.push({ path: file.path, relation: "configuration-reference" });
      else if (directories.has(relative) && /^[.\w/-]+$/.test(value) && value !== "." && value !== "..") for (const target of files.values()) if (inside(target.path, relative)) target.references.push({ path: file.path, relation: "configuration-directory-reference" });
    }
  }
  for (const [root, manifest] of manifests) {
    if (historical(root + "/") || roles.installed.has(path.posix.join(root, "package.json"))) continue;
    for (const [script, command] of Object.entries(manifest.scripts ?? {})) {
      if (typeof command !== "string" || /^(?:pretest|posttest|test|check|lint|typecheck)(?:$|:)/.test(script)) continue;
      if (/\bhugo(?:\s|$)/.test(command)) {
        const destination = command.match(/(?:--destination|-d)\s+([.\w/-]+)/)?.[1] ?? "public";
        const output = path.posix.normalize(path.posix.join(root, destination));
        for (const target of files.values()) if (inside(target.path, output)) target.producers.push(`${root === "." ? "" : root + "/"}package.json`);
      }
      for (const match of command.matchAll(/[A-Za-z0-9_./-]+\.(?:[cm]?[jt]sx?|py|html?|sh)\b/g)) {
        const target = path.posix.normalize(path.posix.join(root, match[0]));
        if (files.has(target)) files.get(target).references.push({ path: `${root === "." ? "" : root + "/"}package.json`, relation: "script-reference", script });
      }
    }
  }
  const closure = (file) => {
    const seen = new Set(), queue = [file];
    while (queue.length) { const next = queue.pop(); if (seen.has(next.path)) continue; seen.add(next.path); for (const dependency of next.dependencies) queue.push(files.get(dependency)); }
    return [...seen].map((name) => files.get(name));
  };
  const activationWitness = new Map();
  const activated = new Set(), activationQueue = [...files.values()].filter((file) => file.references.length);
  for (const file of activationQueue) {
    const root = file.references[0];
    activationWitness.set(file.path, [{ path: root.path, relation: root.relation }, { path: file.path, relation: "declared-entry" }]);
  }
  while (activationQueue.length) {
    const file = activationQueue.pop();
    if (activated.has(file.path)) continue;
    activated.add(file.path);
    for (const target of file.dependencies) {
      const dependency = files.get(target);
      dependency.references.push({ path: file.path, relation: "imported-by-declared-entry" });
      if (!activationWitness.has(target)) activationWitness.set(target, [...activationWitness.get(file.path), { path: target, relation: "import" }]);
      if (!activated.has(target)) activationQueue.push(dependency);
    }
  }
  for (const file of files.values()) {
    if (!activated.has(file.path) && historical(file.path)) continue;
    for (const target of file.source?.outputs ?? []) {
      // Literal writes are relative to process cwd, so only an explicit package
      // script invoking this producer proves the package-relative output base.
      const manifest = manifests.get(file.owner);
      const relative = file.owner ? path.posix.relative(file.owner, file.path) : file.path;
      if (Object.values(manifest?.scripts ?? {}).some((command) => command.includes(relative))) {
        const output = path.posix.normalize(path.posix.join(file.owner ?? ".", target));
        if (files.has(output)) files.get(output).producers.push(file.path);
      }
    }
  }
  const evidence = (reachable, kind) => reachable.flatMap((file) => (file.source?.signals ?? []).filter((signal) => signal.kind === kind).map((signal) => ({ path: file.path, ...signal })));
  for (const file of files.values()) {
    if (!file.text) continue;
    const source = file.source, signals = [...source?.signals ?? [], ...file.missingTargets.map((target) => ({ kind: "unresolved-deployment-entry", line: 1, target }))];
    if (file.manifest) {
      for (const [script, command] of Object.entries(file.manifest.scripts ?? {})) if (typeof command === "string" && /(?:python\S*\s+-m\s+http\.server|(?:^|[ &])(?:npx\s+)?(?:http-server|serve|vite|next\s+(?:dev|start)|hugo\s+server)(?:\s|$))/.test(command)) signals.push({ kind: "external-server-launch", line: 1, script });
      if (!signals.length) continue;
    }
    if (html.test(file.path)) signals.push({ kind: "html-artifact", line: 1 });
    if (other.test(file.path) && /(?:HTTPServer|SimpleHTTPRequestHandler|BaseHTTPRequestHandler|Flask\(|FastAPI\(|uvicorn|http\.ListenAndServe|http\.Serve\(|actix_web|axum::|Sinatra|Plug\.Cowboy|php\s+-S|python\S*\s+-m\s+http\.server)/.test(file.text)) signals.push({ kind: "other-language-server", line: 1 });
    if (/(?:^|\/)(?:hugo|config)\.(?:toml|ya?ml)$/.test(file.path) && (/(?:^|\/)hugo\./.test(file.path) || /^\s*baseURL\s*[:=]/mi.test(file.text))) signals.push({ kind: "site-generator-configuration", line: 1 });
    if (config.test(file.path) && !signals.length) {
      if (/Caddyfile/.test(file.path)) signals.push({ kind: "vendor-transport-configuration", line: 1 });
      else if (/(?:wrangler|site-admin\.config|Dockerfile|\.service$)/.test(file.path) || /(?:wrangler|cloudflare|hugo|http-server|serve.*\.m?[jt]s)/.test(file.text)) signals.push({ kind: "deployment-configuration", line: 1 });
    }
    const declared = source?.imports.filter((entry) => [TUFTE, SERVER, ...LEGACY_SERVERS].some((name) => entry.specifier === name || entry.specifier?.startsWith(name + "/"))) ?? [];
    if (!signals.length && !declared.length && !source?.unknowns.length) continue;
    const manifest = manifests.get(file.owner), packageName = manifest?.name ?? null;
    const isFixture = fixture(file.path) && !file.references.length && !file.producers.length, frontend = signals.some((signal) => /^(?:html-|jsx-|raw-frontend-escape|tufte-render-call|alternative-frontend|site-generator)/.test(signal.kind));
    const server = signals.some((signal) => /^(?:native-|fetch-handler|alternative-server|shared-server|other-language-server|legacy-server-family-call|external-server-launch|unresolved-deployment-entry)/.test(signal.kind));
    const reachable = closure(file), renderEvidence = evidence(reachable, "tufte-render-call"), serverEvidence = evidence(reachable, "shared-server-call");
    const rawNode = signals.some((signal) => signal.kind === "native-node-server" || signal.kind === "alternative-server-framework" || signal.kind === "native-fetch-server" || signal.kind === "other-language-server");
    const unknowns = [...new Set(reachable.flatMap((entry) => entry.source?.unknowns ?? []))].sort();
    const plausibleApplication = frontend || server || applicationPath(file.path) || declared.some((entry) => entry.name && /(?:renderTufte|createFetchHandler)/.test(entry.name));
    const classify = () => {
      if (roles.installed.has(file.path)) return "installed-dependency";
      if (roles.testOutputs.has(file.path) && !activated.has(file.path)) return "generated-test-artifact";
      if (roles.upstream.has(file.path) && !server && !signals.some((signal) => ["jsx-construction", "alternative-frontend-framework"].includes(signal.kind))) return "upstream-web-primitive";
      if (isFixture) return "test-fixture";
      if (historical(file.path) && !activated.has(file.path) && !file.producers.length) return "documentary-or-historical-source";
      if (file.generated || file.producers.length) return "generated-artifact";
      if (signals.some((s) => s.kind === "vendor-transport-configuration")) return "vendor-transport";
      if (signals.some((s) => /configuration$/.test(s.kind))) return "deployment-or-generator-configuration";
      if (roles.engineModules.has(file.path)) return "shared-engine";
      if (frontend) return /(?:^|\/)(?:examples?|demo|dev)(?:\/)/.test(file.path) ? "visible-development-frontend" : "authored-frontend";
      if (server) return "authored-server";
      if (signals.some((s) => ["transport-import", "shared-support-call", "legacy-support-call", "vector-graphic-serialization"].includes(s.kind)) && !unknowns.length) return "reusable-codec-or-transport";
      return plausibleApplication ? "unproven-activation" : "supporting-source";
    };
    const classification = classify();
    const verdict = (required, kind) => {
      if (!required || isFixture || classification === "vendor-transport" || classification === "shared-engine" || ["documentary-or-historical-source", "installed-dependency", "generated-test-artifact", "upstream-web-primitive"].includes(classification)) return { status: "not-applicable", reasons: [], evidence: [] };
      if (classification === "unproven-activation") return { status: "unknown", reasons: ["source-activation-or-role-unproven", ...unknowns], evidence: [] };
      if (classification === "generated-artifact") {
        if (!file.producers.length) return { status: "unknown", reasons: ["generated-artifact-without-proven-producer"], evidence: [] };
        const producers = file.producers.map((producer) => files.get(producer));
        const producerGraph = producers.flatMap(closure);
        const proof = evidence(producerGraph, kind === "frontend" ? "tufte-render-call" : "shared-server-call");
        const incomplete = [...new Set(producerGraph.flatMap((entry) => entry.source?.unknowns ?? []))];
        return { status: incomplete.length ? "unknown" : proof.length ? "conformant" : "nonconformant", reasons: incomplete.length ? incomplete : proof.length ? [] : ["producer-does-not-use-required-engine"], evidence: proof };
      }
      const proof = kind === "frontend" ? renderEvidence : serverEvidence;
      if (kind === "server" && file.missingTargets.length) return { status: "unknown", reasons: ["unresolved-deployment-entry"], evidence: file.missingTargets.map((target) => ({ path: target })) };
      if (kind === "server" && signals.some((signal) => signal.kind === "external-server-launch")) return { status: "unknown", reasons: ["external-server-adapter-unproven"], evidence: [] };
      if (kind === "server" && signals.some((signal) => signal.kind === "other-language-server")) return { status: "unknown", reasons: ["unsupported-server-language-analysis", "no-common-server-path"], evidence: [] };
      if (kind === "server" && rawNode) return { status: "nonconformant", reasons: ["competing-server-construction"], evidence: proof };
      if (kind === "frontend" && proof.length && signals.some((signal) => (signal.kind === "html-construction" && !signal.richTile) || ["raw-frontend-escape", "jsx-construction", "alternative-frontend-framework"].includes(signal.kind))) return { status: "unknown", reasons: ["raw-markup-alongside-tufte-requires-composition-proof"], evidence: proof };
      if (!proof.length) return { status: unknowns.length ? "unknown" : "nonconformant", reasons: [kind === "frontend" ? "no-tufte-render-path" : "no-common-server-path", ...unknowns], evidence: [] };
      return { status: unknowns.length ? "unknown" : "conformant", reasons: unknowns, evidence: proof };
    };
    const frontendResult = verdict(frontend, "frontend"), serverResult = verdict(server, "server");
    const conformance = [frontendResult, serverResult];
    const incomplete = classification === "unproven-activation" && plausibleApplication;
    records.push({ path: file.path, owner: file.owner, package: packageName, classification, frontend, server, signals,
      activation: { status: file.references.length ? "declared" : "unproven", references: file.references, chain: activationWitness.get(file.path) ?? [], installed: "unobserved", published: "unobserved", live: "unobserved" },
      roleEvidence: roles.installed.get(file.path) ?? roles.testOutputs.get(file.path) ?? roles.upstream.get(file.path) ?? roles.engineModules.get(file.path) ?? null,
      producers: file.producers, declaredImports: declared, unknowns, frontendConformance: frontendResult, serverConformance: serverResult,
      status: conformance.some((result) => result.status === "nonconformant") ? "nonconformant" : incomplete || conformance.some((result) => result.status === "unknown") ? "unknown" : conformance.some((result) => result.status === "conformant") ? "conformant" : "not-applicable",
    });
  }
  const count = (key) => Object.fromEntries([...new Set(records.map((row) => row[key]))].sort().map((value) => [value, records.filter((row) => row[key] === value).length]));
  const summary = { requiredFrontendRecords: records.filter((r) => r.frontendConformance.status !== "not-applicable").length, requiredServerRecords: records.filter((r) => r.serverConformance.status !== "not-applicable").length, filesRead: snapshot.files.length, packagesRead: manifests.size, records: records.length, frontendRecords: records.filter((r) => r.frontend).length, serverRecords: records.filter((r) => r.server).length, byClassification: count("classification"), byStatus: count("status"), discoveryIssues: issues.length };
  const migrations = records.flatMap((record) => {
    const requirements = [["frontend", record.frontendConformance, TUFTE], ["server", record.serverConformance, SERVER]];
    const changes = requirements.filter(([, result]) => ["nonconformant", "unknown"].includes(result.status)).map(([capability, result, receiver]) => ({ path: record.path, owner: record.owner, package: record.package, capability, receiver, status: result.status, actions: result.reasons }));
    if (!changes.length && record.status === "unknown") changes.push({ path: record.path, owner: record.owner, package: record.package, capability: "evidence", receiver: "source-evidence", status: record.status, actions: ["resolve-source-activation-and-contract", ...record.unknowns] });
    return changes;
  });
  const familyMap = new Map();
  for (const migration of migrations) {
    const key = `${migration.owner ?? path.posix.dirname(migration.path)}:${migration.receiver}`;
    if (!familyMap.has(key)) familyMap.set(key, { owner: migration.owner, package: migration.package, receiver: migration.receiver, files: [], actions: [] });
    const family = familyMap.get(key);
    family.files.push(migration.path);
    family.actions.push(...migration.actions);
  }
  const families = [...familyMap.values()].map((family) => ({ ...family, files: [...new Set(family.files)].sort(), actions: [...new Set(family.actions)].sort() }));
  const recordIndex = new Map(records.map((record) => [record.path, record]));
  return { kind: "website-administration.web-conformance", schemaVersion: 1, root: snapshot.root, scope: snapshot.scope ?? WEB_SOURCE_SCOPE, summary, issues, diagnostics: roles.diagnostics, records,
    observations: [...files.values()].map((file) => ({ path: file.path, role: recordIndex.get(file.path)?.classification ?? (file.manifest ? "package-manifest" : file.error ? "unreadable" : "no-executable-web-signal" ) })),
    migrations, families, complete: issues.length === 0 && !records.some((r) => ["unknown", "nonconformant"].includes(r.status)) };
}

/** @param {string} root @param {object} [adapters] */
export function readWebConformance(root, adapters) { return projectWebConformance(readWebSourceSnapshot(root, adapters)); }
